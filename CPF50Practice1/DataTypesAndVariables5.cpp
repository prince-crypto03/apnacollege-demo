// Task 5: Sum of two integers
#include <iostream>
using namespace std;

int main() {
    int num1, num2, sum;

    cout << "Enter first integer: ";
    cin >> num1;

    cout << "Enter second integer: ";
    cin >> num2;

    sum = num1 + num2;

    cout << "Sum = " << sum << endl;

    return 0;
}
